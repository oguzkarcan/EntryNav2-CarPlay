// End-to-end host test (Phase 2 P8): a simulated iPhone drives the complete accessory stack through
// one whole CarPlay AirPlay session.
//
// The iPhone side ("SimPhone") is written from the PROTOCOL's point of view and never looks into
// accessory internals:
//   * its own SRP-6a client (pair-setup M1/M3/M5, M4 proof and M6 signature checks), learning the
//     accessory id + LTPK only from M6;
//   * its own pair-verify client (X25519 + Ed25519, "PV-Msg02/03" nonces built locally);
//   * its own channel keys with the PHONE-side labels: control read = "Control-Read-Encryption-Key",
//     write = "Control-Write-Encryption-Key"; events read = "Events-Write-Encryption-Key", write =
//     "Events-Read-Encryption-Key" (the accessory does not swap the event keys, so the phone reads with
//     the accessory's write label);
//   * its own stream keys HKDF(shared, "DataStream-Salt" + unsigned decimal(id),
//     "DataStream-Output-Encryption-Key"), its own RTP headers / nonces / AAD, its own 128-byte screen
//     headers, its own NTP packets and big-endian LPCM sample encoding.
// Library code used on the phone side is limited to generic primitives (Monocypher wrappers, bignum
// modExp, TLV8 / bplist / RTSP framing and the generic ControlCipher frame format).
//
// Everything reaches the accessory exactly as a socket layer would deliver it: Session::onControlBytes
// / onEventBytes for the TCP channels, and the platform-side receivers (simulated here) for the media
// streams, which open packets with keys obtained ONLY through the Session helpers.
//
// The golden path runs twice: once with one write per request and once with every phone byte delivered
// ONE BYTE AT A TIME; the accessory output must be byte-identical (deterministic RNGs).
//
// The SHA-512 pins at the bottom of the file are REGRESSION pins generated by this implementation
// (not external vectors); they guard against silent wire changes anywhere in the stack.

