/// Timing / event / keep-alive sockets. openTiming creates the accessory's NTP ClockSync for the
/// phone's timing port, exactly where the real platform layer would start ntp.start(peer, port).
struct E2ETransport : public session::TransportHost {
    Strings events;
    int32_t peer_timing;
    int close_all;
    std::unique_ptr<ntp::ClockSync> clock;
    E2ETransport() : peer_timing(-1), close_all(0) {}
    virtual bool openTiming(int32_t peer, int32_t& port) {
        events.push_back("timing");
        peer_timing = peer;
        if (peer > 0) {
            clock.reset(new ntp::ClockSync(ntp::wallClockNtpOffsetNs(ntp::ntpFromUnixNanos(kUnixWallNs), kMono0)));
        }
        port = 6001;
        return true;
    }
    virtual bool openEvent(int32_t& port) {
        events.push_back("event");
        port = 6002;
        return true;
    }
    virtual bool openKeepAlive(int32_t& port) {
        events.push_back("keepalive");
        port = 6003;
        return true;
    }
    virtual void closeAll() { ++close_all; }
};

struct E2EMedia : public session::MediaHandler {
    Strings events;
    E2ETransport* transport;
    int64_t now_mono;  // the platform's monotonic clock reading for onFeedback
    int setup_sent;
    Bytes screen_key;
    Bytes main_key;
    Bytes alt_key;
    uint64_t main_id;
    audio::AudioFormat main_format;
    audio::AudioFormat alt_format;
    uint32_t sample_time;

    explicit E2EMedia(E2ETransport* t)
        : transport(t), now_mono(0), setup_sent(0), main_id(0), sample_time(0) {}

    virtual bool onScreen(session::Session& s, int32_t type, const bplist::Value& st, int32_t& port) {
        events.push_back("screen:" + dec(static_cast<uint64_t>(type)));
        if (type != info::kStreamTypeMainScreen) return false;
        screen_key.assign(32, 0);
        if (!s.streamOutputKey(st, &screen_key[0])) {
            screen_key.clear();
            return false;
        }
        port = 7100;
        return true;
    }
    virtual bool onAudio(session::Session& s, int32_t type, const bplist::Value& st, bplist::Value& r) {
        events.push_back("audio:" + dec(static_cast<uint64_t>(type)));
        const bplist::Value* idv = st.find("streamConnectionID");
        uint64_t id = 0;
        if (idv == NULL || !session::Session::plistUnsignedId(*idv, id)) return false;
        Bytes key(32, 0);
        if (!s.streamOutputKey(st, &key[0])) return false;
        uint64_t bits = 0;
        const bplist::Value* f = st.find("audioFormat");
        if (f != NULL) session::Session::plistUnsignedId(*f, bits);
        const audio::AudioFormat fmt = audio::formatFromBits(bits, type, strAt(st, "audioType"));
        if (type == info::kStreamTypeMainAudio) {
            main_key = key;
            main_id = id;
            main_format = fmt;
        } else {
            alt_key = key;
            alt_format = fmt;
        }
        r = dict();
        r.set("type", num(type));
        r.set("dataPort", num(type == info::kStreamTypeMainAudio ? 7001 : 7011));
        r.set("controlPort", num(type == info::kStreamTypeMainAudio ? 7002 : 7012));
        r.set("streamConnectionID", bplist::Value::makeUInt(id));
        return true;
    }
    /// CarPlayMediaEngine.onFeedback shape: {streams:[{type, sampleRate, streamConnectionID,
    /// timestamp (synced NTP), sampleTime}]}.
    virtual bool onFeedback(session::Session&, bplist::Value& r) {
        events.push_back("feedback");
        bplist::Value e = dict();
        e.set("type", num(info::kStreamTypeMainAudio));
        e.set("sampleRate", num(main_format.rtp_clock_rate));
        e.set("streamConnectionID", bplist::Value::makeUInt(main_id));
        const uint64_t ts = transport->clock.get() != NULL ? transport->clock->syncedNtp(now_mono) : 0U;
        e.set("timestamp", bplist::Value::makeUInt(ts));
        e.set("sampleTime", num(sample_time));
        bplist::Value::Array a;
        a.push_back(e);
        r = dict();
        r.set("streams", bplist::Value::makeArray(a));
        return true;
    }
    virtual void onTeardown(session::Session&, int32_t type) {
        events.push_back("teardown:" + dec(static_cast<uint64_t>(type)));
    }
    virtual void onAudioDuck(session::Session&, bool ducked) { events.push_back(ducked ? "duck" : "unduck"); }
    virtual void onSetupResponseSent(session::Session&) { ++setup_sent; }
    virtual void onSessionClosed(session::Session&) { events.push_back("closed"); }
};

