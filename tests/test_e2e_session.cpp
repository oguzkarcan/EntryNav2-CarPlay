uint64_t phoneNtp(int64_t ns) {  // phone's own NTP 32.32 conversion (ns >= 0)
    const uint64_t u = static_cast<uint64_t>(ns);
    const uint64_t sec = u / 1000000000ULL;
    const uint64_t rem = u % 1000000000ULL;
    return (sec << 32) | ((rem << 32) / 1000000000ULL);
}

Bytes screenHeader(uint16_t opcode, uint32_t body_size, uint64_t ntp_le, float w, float h) {
    Bytes hd(128, 0);
    putLe(hd, 0, body_size, 4);
    putLe(hd, 4, opcode, 2);
    putLe(hd, 8, ntp_le, 8);
    if (opcode == 1) {
        uint32_t wb = 0, hb = 0;
        memcpy(&wb, &w, 4);
        memcpy(&hb, &h, 4);
        putLe(hd, 16, wb, 4);
        putLe(hd, 20, hb, 4);
    }
    return hd;
}

const uint8_t kSps[] = {0x67, 0x64, 0x00, 0x1f, 0xac, 0xd9, 0x40, 0x50, 0x05, 0xbb, 0x01, 0x10};
const uint8_t kPps[] = {0x68, 0xeb, 0xe3, 0xcb, 0x22, 0xc0};

Bytes avcC() {
    Bytes b = hexToBytes("0164001fffe1");
    b.push_back(0x00);
    b.push_back(static_cast<uint8_t>(sizeof(kSps)));
    b.insert(b.end(), kSps, kSps + sizeof(kSps));
    b.push_back(0x01);
    b.push_back(0x00);
    b.push_back(static_cast<uint8_t>(sizeof(kPps)));
    b.insert(b.end(), kPps, kPps + sizeof(kPps));
    return b;
}

/// Length-prefixed (4-byte BE) access unit of the given NAL units.
Bytes accessUnit(const std::vector<Bytes>& nals, Bytes& annexb_expected) {
    Bytes out;
    annexb_expected.clear();
    for (size_t i = 0; i < nals.size(); ++i) {
        Bytes len(4, 0);
        putBe(len, 0, nals[i].size(), 4);
        cat(out, len);
        cat(out, nals[i]);
        cat(annexb_expected, hexToBytes("00000001"));
        cat(annexb_expected, nals[i]);
    }
    return out;
}

/// Phone RTP packet: [V2 PT96 seq ts ssrc | ct | tag | tail8 = LE counter], AAD = header[4..12].
Bytes rtpPacket(const Bytes& key, uint16_t seq, uint32_t ts, const std::vector<int16_t>& samples, uint64_t counter) {
    Bytes hd(12, 0);
    hd[0] = 0x80;
    hd[1] = 0x60;
    putBe(hd, 2, seq, 2);
    putBe(hd, 4, ts, 4);
    putBe(hd, 8, kAudioSsrc, 4);
    Bytes payload(samples.size() * 2U, 0);
    for (size_t i = 0; i < samples.size(); ++i) {
        putBe(payload, 2U * i, static_cast<uint16_t>(samples[i]), 2);  // CarPlay LPCM is big-endian
    }
    const Bytes aad(hd.begin() + 4, hd.end());
    const Bytes sealed = sealWith(key, counterNonce(counter), aad, payload);
    Bytes pkt = hd;
    cat(pkt, sealed);
    Bytes tail(8, 0);
    putLe(tail, 0, counter, 8);
    cat(pkt, tail);
    return pkt;
}

std::vector<int16_t> samplesFor(uint16_t seq) {
    std::vector<int16_t> s;
    const int base = (static_cast<int>(seq) - 1000) * 1000 - 3500;
    for (int i = 0; i < 8; ++i) s.push_back(static_cast<int16_t>(base + i * 7));  // 4 stereo frames
    if (seq == 1005) {
        s[0] = -32768;
        s[1] = 32767;
    }
    return s;
}

