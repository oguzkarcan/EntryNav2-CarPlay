TEST_CASE(reconnectWithStoredPairingThenUnknownController) {
    GoldenFixture& g = golden();
    REQUIRE(g.chunked.completed);
    // Second control connection: same identity + the store filled by A's pair-setup, no pair-setup.
    {
        Rig rig(g.env, "e2e-accessory-rng-2");
        SimPhone phone(false, "e2e-phone-ltsk", kControllerId, "e2e-phone-eph-2");
        phone.acc_id = g.chunked.acc_id;
        phone.acc_ltpk = g.chunked.acc_ltpk;
        REQUIRE(phone.pairVerify(*rig.s));
        CHECK(rig.s->encrypted());
        CHECK_EQ(std::string(kControllerId), rig.s->controllerId());
        Reply r;
        REQUIRE(phone.call(*rig.s, "GET", "/info", "", Bytes(), r));
        CHECK_EQ(200, r.status);
        CHECK_BYTES_EQ(g.chunked.info_plain, r.raw.body);
        REQUIRE(phone.callPlist(*rig.s, "SETUP", "rtsp://169.254.1.2/1", sessionSetupBody(), r));
        CHECK_EQ(200, r.status);
        CHECK_EQ(1U, g.env.store.size());
    }
    // Third connection: same identity, EMPTY store -> pair-verify M4 is the error TLV.
    {
        AccessoryEnv empty;
        Rig rig(empty, "e2e-accessory-rng-3");
        SimPhone phone(false, "e2e-phone-ltsk", kControllerId, "e2e-phone-eph-3");
        phone.acc_id = g.chunked.acc_id;
        phone.acc_ltpk = g.chunked.acc_ltpk;
        Bytes m4;
        CHECK(!phone.pairVerify(*rig.s, &m4));
        CHECK_BYTES_EQ(hexToBytes("060104070102"), m4);  // state 4, error 2 (authentication)
        CHECK(!rig.s->encrypted());
        CHECK(!rig.s->closed());
        CHECK(rig.s->controllerId().empty());
        uint8_t k[32];
        CHECK(!rig.s->sharedSecret(k));
        CHECK(!rig.s->deriveScreenStreamKey(kScreenConnId, k));
        // Session requests are refused on the unverified (plaintext) connection, with no side effects.
        Reply r;
        REQUIRE(phone.callPlist(*rig.s, "SETUP", "rtsp://169.254.1.2/1", sessionSetupBody(), r));
        CHECK_EQ(403, r.status);
        CHECK_EQ(std::string("Forbidden"), r.reason);
        REQUIRE(phone.call(*rig.s, "RECORD", "rtsp://169.254.1.2/1", "", Bytes(), r));
        CHECK_EQ(403, r.status);
        CHECK(rig.transport.events.empty());
        CHECK(rig.listener.events.empty());
        CHECK(rig.media.events.empty());
        // /info still answers in plaintext.
        REQUIRE(phone.call(*rig.s, "GET", "/info", "", Bytes(), r));
        CHECK_EQ(200, r.status);
        CHECK(!rig.s->closed());
        // An event connection cannot be started without a verified pair-verify: the session closes.
        Bytes out;
        CHECK(!rig.s->onEventAccepted(out));
        CHECK(out.empty());
        CHECK(rig.s->closed());
        CHECK_EQ(1, rig.listener.ended);
        CHECK_EQ(0U, empty.store.size());
    }
}

