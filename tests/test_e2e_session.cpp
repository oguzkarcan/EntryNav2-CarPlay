Bytes sha(const Bytes& data) {
    Bytes out(64);
    crypto::sha512(data.empty() ? NULL : &data[0], data.size(), &out[0]);
    return out;
}
Bytes strBytes(const std::string& s) { return Bytes(s.begin(), s.end()); }
Bytes shaStr(const std::string& s) { return sha(strBytes(s)); }
Bytes prefix(const Bytes& v, size_t n) { return Bytes(v.begin(), v.begin() + static_cast<long>(n)); }
void cat(Bytes& out, const Bytes& v) { out.insert(out.end(), v.begin(), v.end()); }
Bytes arr(const uint8_t* p, size_t n) { return Bytes(p, p + n); }

Bytes hkdf(const Bytes& ikm, const std::string& salt, const std::string& info_label) {
    Bytes out;
    crypto::hkdfSha512(ikm, salt, info_label, 32, out);
    return out;
}

/// Phone-side unsigned decimal (independent of rtsp::toDecimalUnsigned / audio::unsignedDecimal).
std::string dec(uint64_t v) {
    if (v == 0) return "0";
    std::string s;
    while (v != 0) {
        s.insert(s.begin(), static_cast<char>('0' + static_cast<int>(v % 10U)));
        v /= 10U;
    }
    return s;
}

void putLe(Bytes& b, size_t off, uint64_t v, size_t n) {
    for (size_t i = 0; i < n; ++i) b[off + i] = static_cast<uint8_t>(v >> (8U * i));
}
void putBe(Bytes& b, size_t off, uint64_t v, size_t n) {
    for (size_t i = 0; i < n; ++i) b[off + i] = static_cast<uint8_t>(v >> (8U * (n - 1U - i)));
}
uint64_t getBe(const Bytes& b, size_t off, size_t n) {
    uint64_t v = 0;
    for (size_t i = 0; i < n; ++i) v = (v << 8) | b[off + i];
    return v;
}

Bytes labelNonce(const char* label) {
    Bytes n(12, 0);
    memcpy(&n[4], label, 8);
    return n;
}
Bytes counterNonce(uint64_t counter) {
    Bytes n(12, 0);
    putLe(n, 4, counter, 8);
    return n;
}

Bytes sealWith(const Bytes& key, const Bytes& nonce, const Bytes& aad, const Bytes& plain) {
    Bytes out;
    crypto::chacha20Poly1305Seal(&key[0], &nonce[0], aad.empty() ? NULL : &aad[0], aad.size(),
                                 plain.empty() ? NULL : &plain[0], plain.size(), out);
    return out;
}
bool openWith(const Bytes& key, const Bytes& nonce, const Bytes& sealed, Bytes& plain) {
    return crypto::chacha20Poly1305Open(&key[0], &nonce[0], NULL, 0, sealed.empty() ? NULL : &sealed[0],
                                        sealed.size(), plain);
}

