TEST_CASE(transcriptRegressionPins) {
    GoldenFixture& g = golden();
    REQUIRE(g.chunked.completed);
    const std::string plain_hash = bytesToHex(sha(g.chunked.acc_plain));
    Bytes enc = g.chunked.acc_enc;
    cat(enc, g.chunked.acc_events);
    const std::string enc_hash = bytesToHex(sha(enc));
    std::printf("  [info] plaintext-phase bytes=%u sha512=%s\n", static_cast<unsigned>(g.chunked.acc_plain.size()),
                plain_hash.c_str());
    std::printf("  [info] encrypted transcript bytes=%u (control %u + event %u) sha512=%s\n",
                static_cast<unsigned>(enc.size()), static_cast<unsigned>(g.chunked.acc_enc.size()),
                static_cast<unsigned>(g.chunked.acc_events.size()), enc_hash.c_str());
    CHECK_EQ(std::string(kPinPlainPhase), plain_hash);
    CHECK_EQ(std::string(kPinEncryptedTranscript), enc_hash);
}

