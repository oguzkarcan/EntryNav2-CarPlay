struct SimPhone {
    bool bytewise;
    Controller ctrl;
    std::string acc_id;  // learned from M6 (or remembered from an earlier pair-setup)
    Bytes acc_ltpk;
    crypto::X25519KeyPair eph;
    Bytes acc_eph;
    Bytes shared;
    std::unique_ptr<ControlCipher> control;
    std::unique_ptr<ControlCipher> events;
    rtsp::Parser ev_parser;
    uint32_t last_ev_cseq;  // CSeq of the last accessory event command seen
    uint32_t ev_cseq;       // CSeq of phone-originated event requests
    uint32_t cseq;
    int requests;
    // Every byte the accessory emitted, by phase.
    Bytes acc_plain;   // control channel before the phone switched to encryption (incl. M4)
    Bytes acc_enc;     // control channel afterwards
    Bytes acc_events;  // event channel

    SimPhone(bool byte_at_a_time, const std::string& ltsk_label, const std::string& id, const std::string& eph_label)
        : bytewise(byte_at_a_time), ctrl(ltsk_label, id), last_ev_cseq(0), ev_cseq(0), cseq(0), requests(0) {
        const Bytes s = prefix(shaStr(eph_label), 32);
        crypto::x25519FromSecret(&s[0], eph);
    }

    Bytes ephPub() const { return arr(eph.public_key, 32); }

    Bytes build(const std::string& method, const std::string& path, const std::string& ctype, const Bytes& body,
                const rtsp::HeaderList* extra = NULL) {
        rtsp::HeaderList h;
        if (!ctype.empty()) h.push_back(rtsp::Header("Content-Type", ctype));
        if (extra != NULL) h.insert(h.end(), extra->begin(), extra->end());
        h.push_back(rtsp::Header("CSeq", dec(++cseq)));
        h.push_back(rtsp::Header("User-Agent", "AirPlay/770.8.1"));
        Bytes out;
        rtsp::buildRequest(method, path, "RTSP/1.0", h, body, out);
        return out;
    }

    /// Hands raw wire bytes to the control socket (whole or byte by byte); collects the output.
    bool deliver(session::Session& s, const Bytes& wire, Bytes& out) {
        out.clear();
        bool ok = true;
        if (!bytewise) {
            ok = s.onControlBytes(wire.empty() ? NULL : &wire[0], wire.size(), out);
        } else {
            for (size_t i = 0; i < wire.size() && ok; ++i) {
                Bytes chunk;
                ok = s.onControlBytes(&wire[i], 1, chunk);
                cat(out, chunk);
            }
        }
        cat(control.get() != NULL ? acc_enc : acc_plain, out);
        return ok;
    }

    bool parseReplies(const Bytes& raw, bool encrypted, std::vector<Reply>& replies) {
        Bytes plain;
        if (encrypted) {
            if (!control->feed(raw, plain)) return false;
        } else {
            plain = raw;
        }
        rtsp::Parser p;
        std::vector<rtsp::Request> msgs;
        if (!p.feed(plain, msgs) || p.bufferedBytes() != 0) return false;
        replies.clear();
        for (size_t i = 0; i < msgs.size(); ++i) {
            if (!msgs[i].isResponse()) return false;
            Reply r;
            r.status = atoi(msgs[i].path.c_str());
            r.reason = msgs[i].protocol;
            r.raw = msgs[i];
            replies.push_back(r);
        }
        return true;
    }

    /// One request -> exactly one reply whose CSeq matches.
    bool call(session::Session& s, const std::string& method, const std::string& path, const std::string& ctype,
              const Bytes& body, Reply& reply, const rtsp::HeaderList* extra = NULL) {
        const Bytes plain = build(method, path, ctype, body, extra);
        const bool encrypted = control.get() != NULL;
        Bytes wire;
        if (encrypted) {
            if (!control->encrypt(plain, wire)) return false;
            if (startsWith(wire, method)) return false;  // ciphertext, not RTSP
        } else {
            wire = plain;
        }
        Bytes raw;
        ++requests;
        if (!deliver(s, wire, raw)) return false;
        if (encrypted && startsWith(raw, "RTSP/")) return false;  // response must be ciphertext too
        std::vector<Reply> replies;
        if (!parseReplies(raw, encrypted, replies) || replies.size() != 1U) return false;
        reply = replies[0];
        return reply.raw.header("cseq") == dec(cseq);
    }

    bool callPlist(session::Session& s, const std::string& method, const std::string& path,
                   const bplist::Value& body, Reply& reply) {
        return call(s, method, path, rtsp::kContentTypeBinaryPlist, encode(body), reply);
    }

    bool callTlv(session::Session& s, const std::string& path, const Items& items, Items& resp_items, Bytes* raw_body = NULL) {
        Reply r;
        if (!call(s, "POST", path, rtsp::kContentTypePairingTlv8, tlv8::encode(items), r)) return false;
        if (r.status != 200 || r.raw.header("content-type") != rtsp::kContentTypePairingTlv8) return false;
        if (raw_body != NULL) *raw_body = r.raw.body;
        return tlv8::decode(r.raw.body, resp_items);
    }

    // ---- Pair-Setup ----

    bool setupM1(session::Session& s, Bytes& b_pub, Bytes& salt) {
        Items req;
        req.push_back(tlv8::Item(tlv8::kTagMethod, Bytes(1, 0)));
        req.push_back(tlv8::Item::fromByte(tlv8::kTagState, 1));
        Items m2;
        if (!callTlv(s, "/pair-setup", req, m2)) return false;
        if (typesOf(m2) != hexToBytes("060302") || valueOf(m2, tlv8::kTagState) != Bytes(1, 2)) return false;
        b_pub = valueOf(m2, tlv8::kTagPublicKey);
        salt = valueOf(m2, tlv8::kTagSalt);
        return b_pub.size() == 384 && salt.size() == 16;
    }

    /// M3; returns the M4 body. true only for a valid M4 whose proof the client verified.
    bool setupM3(session::Session& s, const SrpClient& c, Bytes& m4_body) {
        Items req;
        req.push_back(tlv8::Item::fromByte(tlv8::kTagState, 3));
        req.push_back(tlv8::Item(tlv8::kTagPublicKey, c.a_pub));
        req.push_back(tlv8::Item(tlv8::kTagProof, c.m1));
        Items m4;
        if (!callTlv(s, "/pair-setup", req, m4, &m4_body)) return false;
        return typesOf(m4) == hexToBytes("0604") && valueOf(m4, tlv8::kTagState) == Bytes(1, 4) &&
               valueOf(m4, tlv8::kTagProof) == c.m2;
    }

    /// M5 -> M6: verifies the accessory's signature and learns its id + LTPK from M6 only.
    bool setupM5(session::Session& s, const Bytes& k) {
        const Bytes enc_key = hkdf(k, "Pair-Setup-Encrypt-Salt", "Pair-Setup-Encrypt-Info");
        Bytes data = hkdf(k, "Pair-Setup-Controller-Sign-Salt", "Pair-Setup-Controller-Sign-Info");
        cat(data, strBytes(ctrl.id));
        cat(data, ctrl.ltpk());
        Items sub;
        sub.push_back(tlv8::Item(tlv8::kTagIdentifier, strBytes(ctrl.id)));
        sub.push_back(tlv8::Item(tlv8::kTagPublicKey, ctrl.ltpk()));
        sub.push_back(tlv8::Item(tlv8::kTagSignature, ctrl.sign(data)));
        Items req;
        req.push_back(tlv8::Item::fromByte(tlv8::kTagState, 5));
        req.push_back(tlv8::Item(tlv8::kTagEncryptedData, sealWith(enc_key, labelNonce("PS-Msg05"), Bytes(), tlv8::encode(sub))));
        Items m6;
        if (!callTlv(s, "/pair-setup", req, m6)) return false;
        if (typesOf(m6) != hexToBytes("0605") || valueOf(m6, tlv8::kTagState) != Bytes(1, 6)) return false;
        Bytes plain;
        if (!openWith(enc_key, labelNonce("PS-Msg06"), valueOf(m6, tlv8::kTagEncryptedData), plain)) return false;
        Items acc;
        if (!tlv8::decode(plain, acc) || typesOf(acc) != hexToBytes("01030a")) return false;
        const Bytes id = valueOf(acc, tlv8::kTagIdentifier);
        const Bytes ltpk = valueOf(acc, tlv8::kTagPublicKey);
        const Bytes sig = valueOf(acc, tlv8::kTagSignature);
        if (id.empty() || ltpk.size() != 32 || sig.size() != 64) return false;
        Bytes signed_data = hkdf(k, "Pair-Setup-Accessory-Sign-Salt", "Pair-Setup-Accessory-Sign-Info");
        cat(signed_data, id);
        cat(signed_data, ltpk);
        if (!crypto::ed25519Verify(&ltpk[0], &signed_data[0], signed_data.size(), &sig[0])) return false;
        acc_id.assign(id.begin(), id.end());
        acc_ltpk = ltpk;
        return true;
    }

    bool pairSetup(session::Session& s, const std::string& srp_label) {
        Bytes b_pub, salt, m4;
        if (!setupM1(s, b_pub, salt)) return false;
        SrpClient c(srp_label);
        if (!c.compute(b_pub, salt, "3939")) return false;
        if (!setupM3(s, c, m4)) return false;
        return setupM5(s, c.k);
    }

    // ---- Pair-Verify ----

    /// M1..M4. true when M4 is the success TLV; then both phone channels are keyed.
    bool pairVerify(session::Session& s, Bytes* m4_out = NULL) {
        Items m1;
        m1.push_back(tlv8::Item::fromByte(tlv8::kTagState, 1));
        m1.push_back(tlv8::Item(tlv8::kTagPublicKey, ephPub()));
        Items m2;
        if (!callTlv(s, "/pair-verify", m1, m2)) return false;
        if (typesOf(m2) != hexToBytes("060305") || valueOf(m2, tlv8::kTagState) != Bytes(1, 2)) return false;
        acc_eph = valueOf(m2, tlv8::kTagPublicKey);
        if (acc_eph.size() != 32 || acc_ltpk.size() != 32) return false;
        shared.assign(32, 0);
        if (!crypto::x25519SharedSecret(eph.secret_key, &acc_eph[0], &shared[0])) return false;
        const Bytes key = hkdf(shared, "Pair-Verify-Encrypt-Salt", "Pair-Verify-Encrypt-Info");
        Bytes plain;
        if (!openWith(key, labelNonce("PV-Msg02"), valueOf(m2, tlv8::kTagEncryptedData), plain)) return false;
        Items sub;
        if (!tlv8::decode(plain, sub) || typesOf(sub) != hexToBytes("010a")) return false;
        if (valueOf(sub, tlv8::kTagIdentifier) != strBytes(acc_id)) return false;
        const Bytes sig = valueOf(sub, tlv8::kTagSignature);
        Bytes data = acc_eph;
        cat(data, strBytes(acc_id));
        cat(data, ephPub());
        if (sig.size() != 64 || !crypto::ed25519Verify(&acc_ltpk[0], &data[0], data.size(), &sig[0])) return false;

        Bytes mine = ephPub();
        cat(mine, strBytes(ctrl.id));
        cat(mine, acc_eph);
        Items sub3;
        sub3.push_back(tlv8::Item(tlv8::kTagIdentifier, strBytes(ctrl.id)));
        sub3.push_back(tlv8::Item(tlv8::kTagSignature, ctrl.sign(mine)));
        Items m3;
        m3.push_back(tlv8::Item::fromByte(tlv8::kTagState, 3));
        m3.push_back(tlv8::Item(tlv8::kTagEncryptedData, sealWith(key, labelNonce("PV-Msg03"), Bytes(), tlv8::encode(sub3))));
        Items m4;
        Bytes m4_body;
        if (!callTlv(s, "/pair-verify", m3, m4, &m4_body)) return false;
        if (m4_out != NULL) *m4_out = m4_body;
        if (m4_body != hexToBytes("060104")) return false;
        keyChannels();
        return true;
    }

    void keyChannels() {
        const Bytes c_read = hkdf(shared, "Control-Salt", "Control-Read-Encryption-Key");
        const Bytes c_write = hkdf(shared, "Control-Salt", "Control-Write-Encryption-Key");
        control.reset(new ControlCipher(&c_read[0], &c_write[0]));
        const Bytes e_read = hkdf(shared, "Events-Salt", "Events-Write-Encryption-Key");
        const Bytes e_write = hkdf(shared, "Events-Salt", "Events-Read-Encryption-Key");
        events.reset(new ControlCipher(&e_read[0], &e_write[0]));
    }

    Bytes streamKey(uint64_t id) const {
        return hkdf(shared, "DataStream-Salt" + dec(id), "DataStream-Output-Encryption-Key");
    }

    // ---- Event channel ----

    /// Decrypts accessory event bytes; every message must be POST /command with a bplist body and a
    /// strictly increasing CSeq.
    bool readEvents(const Bytes& wire, std::vector<rtsp::Request>& reqs) {
        cat(acc_events, wire);
        Bytes plain;
        if (!events->feed(wire, plain)) return false;
        const size_t before = reqs.size();
        if (!ev_parser.feed(plain, reqs)) return false;
        for (size_t i = before; i < reqs.size(); ++i) {
            const rtsp::Request& m = reqs[i];
            if (m.method != "POST" || m.path != "/command" || m.protocol != "RTSP/1.0") return false;
            if (m.header("content-type") != rtsp::kContentTypeBinaryPlist) return false;
            const uint32_t c = static_cast<uint32_t>(strtoul(m.header("cseq").c_str(), NULL, 10));
            if (c <= last_ev_cseq) return false;
            last_ev_cseq = c;
        }
        return true;
    }

    bool deliverEvent(session::Session& s, const Bytes& wire, Bytes& out, std::vector<rtsp::Request>* reqs = NULL) {
        out.clear();
        bool ok = true;
        if (!bytewise) {
            ok = s.onEventBytes(&wire[0], wire.size(), out, reqs);
        } else {
            for (size_t i = 0; i < wire.size() && ok; ++i) {
                Bytes chunk;
                ok = s.onEventBytes(&wire[i], 1, chunk, reqs);
                cat(out, chunk);
            }
        }
        cat(acc_events, out);
        return ok;
    }

    /// Answers each accessory command with an encrypted 200 echoing its CSeq.
    bool answerEvents(session::Session& s, const std::vector<rtsp::Request>& reqs) {
        for (size_t i = 0; i < reqs.size(); ++i) {
            const std::string resp = "RTSP/1.0 200 OK\r\nCSeq: " + reqs[i].header("cseq") + "\r\nContent-Length: 0\r\n\r\n";
            Bytes wire;
            if (!events->encrypt(strBytes(resp), wire)) return false;
            Bytes out;
            if (!deliverEvent(s, wire, out)) return false;
            if (!out.empty()) return false;  // responses are consumed silently
        }
        return true;
    }
};

