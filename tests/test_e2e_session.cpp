Bytes touch12(int d0, int x0, int y0, int d1, int x1, int y1) {
    const int v[12] = {0, d0, x0 & 0xff, x0 >> 8, y0 & 0xff, y0 >> 8, 1, d1, x1 & 0xff, x1 >> 8, y1 & 0xff, y1 >> 8};
    Bytes b;
    for (int i = 0; i < 12; ++i) b.push_back(static_cast<uint8_t>(v[i]));
    return b;
}

struct HidExpect {
    std::string uuid;
    Bytes report;
    HidExpect(const std::string& u, const Bytes& r) : uuid(u), report(r) {}
};

/// The accessory has produced `wire` on the event socket: the phone decrypts it, checks every command
/// against `expect` and answers all of them; the accessory consumes the answers.
bool hidRoundTrip(SimPhone& phone, session::Session& s, const Bytes& wire, const std::vector<HidExpect>& expect) {
    std::vector<rtsp::Request> reqs;
    if (!phone.readEvents(wire, reqs) || reqs.size() != expect.size()) return false;
    for (size_t i = 0; i < reqs.size(); ++i) {
        bplist::Value v;
        if (!bplist::decode(reqs[i].body, v) || !v.isDict()) return false;
        if (join(keysOf(v)) != "type,uuid,hidReport") return false;
        if (strAt(v, "type") != "hidSendReport" || strAt(v, "uuid") != expect[i].uuid) return false;
        const bplist::Value* r = v.find("hidReport");
        if (r == NULL || !r->isData() || r->asData() != expect[i].report) {
            std::printf("  hid mismatch #%u: got %s want %s\n", static_cast<unsigned>(i),
                        r != NULL && r->isData() ? bytesToHex(r->asData()).c_str() : "-",
                        bytesToHex(expect[i].report).c_str());
            return false;
        }
    }
    return phone.answerEvents(s, reqs);
}

