TEST_CASE(truncatedFrameThenSilenceKeepsSessionOpen) {
    PairedRig p;
    session::Session& s = p.s();
    REQUIRE(p.phone.pairVerify(s));
    Bytes wire;
    REQUIRE(p.phone.control->encrypt(p.phone.build("GET", "/info", "", Bytes()), wire));
    REQUIRE(wire.size() > 20U);
    const size_t half = wire.size() / 2;
    Bytes out;
    CHECK(s.onControlBytes(&wire[0], half, out));
    CHECK(out.empty());
    CHECK(!s.closed());
    CHECK(s.encrypted());
    CHECK_EQ(0, p.rig->listener.ended);
    // ... silence. If the rest arrives later the request is still served.
    CHECK(s.onControlBytes(&wire[half], wire.size() - half, out));
    std::vector<Reply> replies;
    REQUIRE(p.phone.parseReplies(out, true, replies));
    REQUIRE(replies.size() == 1U);
    CHECK_EQ(200, replies[0].status);
    // Only the 2-byte length header of the next frame, then nothing.
    out.clear();
    Bytes next;
    REQUIRE(p.phone.control->encrypt(p.phone.build("GET", "/info", "", Bytes()), next));
    CHECK(s.onControlBytes(&next[0], 2, out));
    CHECK(out.empty());
    CHECK(!s.closed());
}

