/// Platform-side screen stream TCP reader (ScreenStream.kt run/onMessage), simulated: splits the byte
/// stream into [128-byte header | body], decrypts frames with the per-frame counter nonce and the
/// header as AAD, converts to Annex B.
struct ScreenReceiver {
    Bytes key;
    uint64_t frame_counter;
    Bytes buf;
    bool failed;
    Bytes config_annexb;
    uint8_t nal_length_bytes;
    float width;
    float height;
    std::vector<Bytes> frames;
    std::vector<uint64_t> frame_sender_nanos;

    explicit ScreenReceiver(const Bytes& k)
        : key(k), frame_counter(0), failed(false), nal_length_bytes(0), width(0), height(0) {}

    bool feed(const uint8_t* d, size_t n) {
        if (failed) return false;
        buf.insert(buf.end(), d, d + n);
        while (buf.size() >= stream::kScreenHeaderBytes) {
            stream::ScreenPacketHeader h;
            if (!stream::parseScreenHeader(&buf[0], buf.size(), h)) return fail();
            const size_t total = stream::kScreenHeaderBytes + h.payload_size;
            if (buf.size() < total) break;
            const uint8_t* body = &buf[stream::kScreenHeaderBytes];
            if (h.opcode == stream::kOpVideoConfig) {
                width = h.width_px;
                height = h.height_px;
                if (stream::detectConfigCodec(body, h.payload_size) != stream::CODEC_H264_AVCC) return fail();
                if (!stream::avcCToAnnexB(body, h.payload_size, config_annexb, &nal_length_bytes)) return fail();
            } else if (h.opcode == stream::kOpVideoFrame) {
                if (h.payload_size < 16U) return fail();
                Bytes plain;
                if (!stream::decryptFrame(&key[0], frame_counter, &buf[0], stream::kScreenHeaderBytes, body,
                                          h.payload_size - 16U, body + h.payload_size - 16U, plain)) {
                    return fail();
                }
                ++frame_counter;
                if (!stream::lengthPrefixedToAnnexB(plain)) return fail();
                frames.push_back(plain);
                frame_sender_nanos.push_back(h.sender_nanos);
            }
            buf.erase(buf.begin(), buf.begin() + static_cast<long>(total));
        }
        return true;
    }
    bool fail() {
        failed = true;
        return false;
    }
};

